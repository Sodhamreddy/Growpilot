import type { TenantContext } from "@ob/core";
import type { Gateway } from "@ob/ai";
import {
  composeSystemPrompt, BASE_SYSTEM_RULES, BASE_SAFETY,
  renderBusinessFacts, PROMPT_VERSIONS,
} from "@ob/ai";

/**
 * Topic pool generation — one category at a time.
 *
 * The pool is built before any calendar exists. A topic belongs to a service
 * line permanently and only borrows a date when a month picks it up, so
 * generation here is dateless: no weekday grid, no observance arithmetic, no
 * chance of last year's date for a moveable feast.
 *
 * The Events category is the exception and is generated by `dated.ts`, which
 * takes a grid and shows its working.
 */

export type SocialAudience =
  | "Senior specific"
  | "Family caregiver specific"
  | "Caregiver specific"
  | "General";

/**
 * Audience segments, taken from the reference planner rather than invented.
 *
 * "Family caregiver specific" and "Caregiver specific" are genuinely
 * different readers — the adult child arranging care, and the paid caregiver
 * doing the work — and collapsing them produces posts that speak to neither.
 */
export const AUDIENCES: SocialAudience[] = [
  "Senior specific",
  "Family caregiver specific",
  "Caregiver specific",
  "General",
];

export const FORMATS = [
  "Static Image", "Carousel", "Video", "Quote", "Q and A", "Poll/Quiz", "Podcast", "GIF",
] as const;

export type SocialFormat = (typeof FORMATS)[number];

export interface PoolTopic {
  title: string;
  /** The argument the post makes, 60-90 words of prose. */
  hook: string;
  audience: SocialAudience;
  format: SocialFormat;
  /** One concrete photographic scene. No text, no logo, no layout. */
  imageIdea: string;
  /** The observance this hangs off, when it hangs off one. */
  occasion: string | null;
  /** "YYYY-MM-DD" when the topic is tied to a day, else null. */
  postDate: string | null;
  /**
   * How the date was derived, e.g. "2nd Thursday of November".
   *
   * Required whenever a date is given. Observances fixed by a rule move every
   * year and reusing last year's date is the likeliest error in this task, so
   * the rule is shown to a reviewer rather than the date asserted alone.
   */
  dateRule: string | null;
  /** The model's own read of whether this belongs in the next month. */
  recommended: boolean;
  recommendedWhy: string | null;
}

export interface RejectedTopic {
  topic: string;
  reason: string;
}

const TOPIC_SCHEMA = {
  type: "object",
  additionalProperties: false,
  required: ["topics", "rejected"],
  properties: {
    topics: {
      type: "array",
      items: {
        type: "object",
        additionalProperties: false,
        required: [
          "title", "hook", "audience", "format", "imageIdea",
          "occasion", "postDate", "dateRule", "recommended", "recommendedWhy",
        ],
        properties: {
          title: { type: "string" },
          hook: { type: "string" },
          audience: { type: "string", enum: AUDIENCES },
          format: { type: "string", enum: FORMATS as unknown as string[] },
          imageIdea: { type: "string" },
          // Nullable fields are typed as strings and emptied by the
          // normaliser: Gemini's schema dialect has no union type, and a
          // nullable declaration it does not understand fails the whole call.
          occasion: { type: "string" },
          postDate: { type: "string" },
          dateRule: { type: "string" },
          recommended: { type: "boolean" },
          recommendedWhy: { type: "string" },
        },
      },
    },
    rejected: {
      type: "array",
      items: {
        type: "object",
        additionalProperties: false,
        required: ["topic", "reason"],
        properties: { topic: { type: "string" }, reason: { type: "string" } },
      },
    },
  },
} as const;

const TOPIC_RULES = `${BASE_SYSTEM_RULES}

You are the content strategist for the brand described below, planning social
topics for ONE service category.

WHAT MAKES A GOOD TOPIC
Every topic is a post that lands on ONE concrete thing a real person can do this
week. Not awareness. Not a ribbon. An action.

  WEAK    "October is X Awareness Month."
  STRONG  "Screening after 75 is a shared decision, not an automatic
           appointment, and booking one when you cannot stand unassisted needs
           two questions asked on the phone first."

Be specific where competitors are vague: name the room, the hour, the number,
the exact sentence to say. "The 4 p.m. window" beats "in the afternoon".

GIVE REASONS, NOT ASSERTIONS. Every claim carries the because behind it.

Reject, and list in "rejected" rather than including:
  - anything tone-deaf, pitying or patronising to the audience
  - trend-chasing or novelty days
  - a tribute post with a sales angle stapled on the end
  - anything matching a title already covered

ACCURACY, NON-NEGOTIABLE
This is healthcare. A fabricated figure is the one mistake that cannot be
walked back.
- Never invent a statistic, study name, dollar amount, deadline or eligibility
  threshold. If a figure is not given to you, describe the pattern in words.
- Write anything that changes yearly as "check the current rule".
- Never tell anyone to start, stop or change a treatment or a dose. Point
  professional decisions back to a qualified professional.
- For anything urgent, the instruction is to seek emergency help, never to wait.

PUNCTUATION, ABSOLUTE
Never use an em dash or an en dash anywhere, in any field. Use a period, a
colon, a comma, a semicolon or parentheses, and pick the one that fits. Two
short sentences almost always beat one sentence held together by a dash.
Hyphens inside compound words are correct.

(These instructions are themselves written without dashes on purpose. A model
imitates the punctuation it is shown.)

NEVER WRITE LIKE AN AI
No "In today's world", "When it comes to", "Let's dive in", "It's important to
note that", "Navigating the journey of". If a line would work unchanged for a
competitor, rewrite it.

MIX
Vary formats deliberately. A category of one format is a bad category.
Spread audiences so no single segment exceeds about half, and every segment
that genuinely fits this category appears at least once.

DATES
TODAY is given below. Every date you produce must be in the future relative to
it. An observance that has already passed this year belongs to next year, so
use next year's date and say so in the rule.

Most topics are not tied to a day. Leave occasion, postDate and dateRule empty
for those: an evergreen topic that can run any week is more useful than one
pinned to a date for no reason.

When a topic genuinely hangs off an observance, give all three. Observances
fixed by a rule move every year, and using last year's date is the most likely
error in this task, so state the rule you computed from:
  "4th Thursday of November"    "the Sunday on or after the 8th"
  "always the 15th"             "2nd Sunday of May"
If you cannot derive the date with confidence, leave postDate empty and say so
in dateRule. A wrong date published on the wrong day is worse than no date.

RECOMMENDED
Mark roughly a third as recommended: the ones you would put in the next month
if you had to choose today. Give a short reason in recommendedWhy, one clause,
what makes it timely or unusually strong. Everything else is recommended false
with recommendedWhy empty. Recommending most of the list tells a reviewer
nothing.`;

export interface PoolInput {
  business: {
    name: string;
    industry: string | null;
    audience: string | null;
    usp: string | null;
    description: string | null;
  };
  facts: {
    key: string;
    value: string;
    sourceUrl?: string | null;
    confidence: number;
    verified: boolean;
  }[];
  locations: string[];
  category: { name: string; description: string };
  /** How many to produce. */
  count: number;
  /** Titles already in the pool, so a second run does not repeat them. */
  existingTitles: string[];
  /** Words the brand does not use. */
  wordsToAvoid: string[];
  /**
   * Today, in the workspace's terms.
   *
   * Without it the model dates observances from its training data: a probe
   * run in September 2026 returned New Year's Day 2025 and Thanksgiving 2024,
   * all of them in the past. A model has no clock, so the one it is not given
   * it invents.
   */
  today?: Date;
}

export interface PoolResult {
  topics: PoolTopic[];
  rejected: RejectedTopic[];
}

export async function generateCategoryTopics(
  gateway: Gateway,
  ctx: TenantContext,
  input: PoolInput,
): Promise<PoolResult> {
  const businessFacts = [
    renderBusinessFacts(input.business, input.facts),
    "",
    input.locations.length > 0
      ? `Places they operate: ${input.locations.join("; ")}`
      : "No specific locations recorded.",
  ].join("\n");

  const avoid = input.existingTitles.length > 0
    ? `\n\nAlready in the pool. Do not propose these or close variants:\n` +
      input.existingTitles.slice(0, 200).map((t) => `  - ${t}`).join("\n")
    : "";

  const banned = input.wordsToAvoid.length > 0
    ? `\n\nWords this brand does not use. Never write them:\n  ${input.wordsToAvoid.join(", ")}`
    : "";

  const today = input.today ?? new Date();
  const todayIso = today.toISOString().slice(0, 10);

  const { system, cacheablePrefixLength } = composeSystemPrompt({
    systemRules: TOPIC_RULES,
    safety: BASE_SAFETY,
    businessFacts,
    task: [
      `TODAY: ${todayIso} (${today.toLocaleDateString("en-US", {
        weekday: "long", month: "long", day: "numeric", year: "numeric", timeZone: "UTC",
      })})`,
      "",
      `CATEGORY: ${input.category.name}`,
      input.category.description ? `WHAT IT COVERS: ${input.category.description}` : "",
      "",
      `Propose exactly ${input.count} social topics for this category.`,
      "",
      "Each topic needs:",
      "  title      A specific sentence. Never a bare observance or service name.",
      "  hook       60 to 90 words of prose: what this post argues, what the",
      "             reader learns, and the ONE action they take. Written as the",
      "             substance of the post, not as instructions to a copywriter.",
      "  audience   One of the configured segments.",
      "  format     One of the configured formats.",
      "  imageIdea  One concrete photographic scene. No text, no logo, no layout.",
      "  occasion   The observance it hangs off, or empty.",
      "  postDate   YYYY-MM-DD, or empty when it is not tied to a day.",
      "  dateRule   How that date was derived. Required if postDate is given.",
      "  recommended      true for about a third, the strongest and most timely.",
      "  recommendedWhy   One clause saying why. Empty when not recommended.",
      banned,
      avoid,
    ].filter(Boolean).join("\n"),
    outputFormat: "Return only JSON conforming to the provided schema. No prose, no code fences.",
  });

  const res = await gateway.generate(ctx, {
    taskAlias: "structured_json",
    system,
    cacheableSystemPrefixLength: cacheablePrefixLength,
    messages: [{ role: "user", content: "Propose the topics now." }],
    schema: TOPIC_SCHEMA as unknown as Record<string, unknown>,
    promptVersion: PROMPT_VERSIONS.businessExtraction,
  });

  return normalise(res.parsed, input);
}

/**
 * Clamp and sanity-check what came back.
 *
 * The schema constrains shape, not sense. Two checks matter beyond it: a
 * duplicate title against the existing pool (the model is told, but 144 titles
 * is a lot to hold), and a dash slipping into any field despite the rule.
 * Dashes are stripped rather than rejected, because losing an otherwise good
 * topic over one character would be a worse trade.
 */
function normalise(parsed: unknown, input: PoolInput): PoolResult {
  const raw = (parsed as { topics?: unknown[]; rejected?: unknown[] } | undefined);
  const list = Array.isArray(raw?.topics) ? raw.topics : [];

  const seen = new Set(input.existingTitles.map((t) => t.toLowerCase().trim()));
  const topics: PoolTopic[] = [];

  for (const entry of list) {
    if (typeof entry !== "object" || entry === null) continue;
    const e = entry as Record<string, unknown>;

    const title = stripDashes(String(e["title"] ?? "")).trim();
    const hook = stripDashes(String(e["hook"] ?? "")).trim();
    if (!title || !hook) continue;

    const key = title.toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);

    const audience = AUDIENCES.includes(e["audience"] as SocialAudience)
      ? (e["audience"] as SocialAudience)
      : "General";
    const format = (FORMATS as readonly string[]).includes(String(e["format"]))
      ? (String(e["format"]) as SocialFormat)
      : "Static Image";

    /*
     * A date is kept only when it parses and carries its rule.
     *
     * The two failures worth guarding are a plausible-looking date that is
     * simply wrong for this year, and a date with no working shown. Neither is
     * detectable later: a post scheduled on the wrong day looks exactly like
     * one scheduled on the right day until it publishes.
     */
    const rawDate = String(e["postDate"] ?? "").trim();
    const dateRule = stripDashes(String(e["dateRule"] ?? "")).trim();
    /*
     * A date in the past is dropped, not kept.
     *
     * The model dates observances from its training data unless told the year,
     * and even told it will occasionally reach for a remembered one. A topic
     * scheduled before today can never run, and keeping it would put a dead
     * date on a card that looks exactly like a live one.
     */
    const wellFormed = /^\d{4}-\d{2}-\d{2}$/.test(rawDate) && !Number.isNaN(Date.parse(rawDate));
    const parsed = wellFormed ? new Date(`${rawDate}T12:00:00Z`) : null;
    const postDate = parsed && dateRule && parsed.getTime() >= startOfToday(input.today)
      ? rawDate
      : null;

    const recommended = e["recommended"] === true;

    topics.push({
      title,
      hook,
      audience,
      format,
      imageIdea: stripDashes(String(e["imageIdea"] ?? "")).trim(),
      occasion: stripDashes(String(e["occasion"] ?? "")).trim() || null,
      postDate,
      dateRule: postDate ? dateRule : null,
      recommended,
      // A reason without a recommendation is noise; a recommendation without
      // a reason is an assertion. Both are dropped to the same empty state.
      recommendedWhy: recommended
        ? stripDashes(String(e["recommendedWhy"] ?? "")).trim() || null
        : null,
    });

    if (topics.length >= input.count) break;
  }

  const rejected: RejectedTopic[] = [];
  for (const entry of Array.isArray(raw?.rejected) ? raw.rejected : []) {
    if (typeof entry !== "object" || entry === null) continue;
    const e = entry as Record<string, unknown>;
    const topic = String(e["topic"] ?? "").trim();
    if (topic) rejected.push({ topic, reason: String(e["reason"] ?? "").trim() });
  }

  return { topics, rejected };
}

/**
 * Remove em and en dashes.
 *
 * The prompt forbids them and the reference planner treats it as absolute, but
 * a model trained on prose full of them will still slip. Replaced with a comma
 * plus space where they sat between words, which is the substitution that reads
 * correctly most of the time; a stray double space is then collapsed.
 */
/** Midnight UTC today, so a date landing on today itself still counts. */
function startOfToday(today?: Date): number {
  const d = today ?? new Date();
  return Date.UTC(d.getUTCFullYear(), d.getUTCMonth(), d.getUTCDate());
}

export function stripDashes(text: string): string {
  return text
    .replace(/\s*[—–]\s*/g, ", ")
    .replace(/\s{2,}/g, " ")
    .replace(/\s+([,.;:!?])/g, "$1")
    .replace(/,\s*,/g, ",");
}
